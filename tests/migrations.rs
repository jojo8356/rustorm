use rustorm::{
    checksum::sha256,
    migrations::{create, initial_sql, load, split_sql},
    schema::{parse, DefaultValue},
};
use std::{
    fs,
    path::PathBuf,
    sync::atomic::{AtomicUsize, Ordering},
};
static NEXT: AtomicUsize = AtomicUsize::new(0);
struct Temp(PathBuf);
impl Temp {
    fn new() -> Self {
        let p = std::env::temp_dir().join(format!(
            "rustorm-migrate-unit-{}-{}",
            std::process::id(),
            NEXT.fetch_add(1, Ordering::Relaxed)
        ));
        fs::create_dir_all(&p).unwrap();
        Self(p)
    }
}
impl Drop for Temp {
    fn drop(&mut self) {
        let _ = fs::remove_dir_all(&self.0);
    }
}
fn schema() -> rustorm::schema::Schema {
    parse(
        r#"datasource db {
 provider = "postgresql"
}
model User {
 id Int @id @default(autoincrement())
 name String @unique @default("O'Reilly\\path")
 note String?
 active Boolean @default(false)
 @@map("users")
}
"#,
    )
    .unwrap()
}
#[test]
fn sha256_matches_standard_vectors() {
    assert_eq!(
        sha256(b""),
        "e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855"
    );
    assert_eq!(
        sha256(b"abc"),
        "ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad"
    );
    assert_eq!(
        sha256(&vec![b'a'; 1_000_000]),
        "cdc76e5c9914fb9281a1c7e284d73e67f1809a48a497200e046d39ccc7112cd0"
    );
}
#[test]
fn generates_deterministic_postgres_sql_with_safe_literals() {
    let s = schema();
    let sql = initial_sql(&s).unwrap();
    assert!(sql.contains("\"id\" INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY"));
    assert!(sql.contains("\"name\" TEXT NOT NULL UNIQUE DEFAULT E'O''Reilly\\\\path'"));
    assert!(sql.contains("\"note\" TEXT"));
    assert_eq!(sql, initial_sql(&s).unwrap());
    assert_eq!(split_sql(&sql).unwrap().len(), 1);
}
#[test]
fn schema_sql_refuses_invalid_or_manually_forged_model() {
    let mut s = schema();
    s.models[0].fields[0].default = Some(DefaultValue::Number("1); DROP TABLE users;--".into()));
    assert!(initial_sql(&s).is_err());
    let mut s = schema();
    s.models[0].table = "_rustorm_migrations".into();
    assert!(initial_sql(&s).is_err());
    let mut s = schema();
    s.models[0].fields[1].column = "x".repeat(64);
    assert!(initial_sql(&s).is_err());
}
#[test]
fn splits_strings_comments_dollar_quotes_and_nested_comments() {
    let sql = "-- ; comment\nCREATE TABLE t (x text DEFAULT ';'); /* outer ; /* nested ; */ end */ INSERT INTO t VALUES (E'a\\\';b'); SELECT $$semi;colon$$;";
    let statements = split_sql(sql).unwrap();
    assert_eq!(statements.len(), 3);
    assert!(statements[1].contains("INSERT"));
    assert!(split_sql("-- no sql\n /* empty */ ;").unwrap().is_empty());
    assert_eq!(
        split_sql("SELECT 1; -- comment\rSELECT 2;").unwrap().len(),
        2
    );
    assert!(split_sql("SELECT 1; -- comment\rCOMMIT;").is_err());
}
#[test]
fn rejects_transaction_control_copy_and_malformed_sql() {
    for sql in [
        "BEGIN; SELECT 1",
        "  /* a */ COMMIT",
        "ROLLBACK",
        "SAVEPOINT hi",
        "COPY t FROM STDIN",
        "DO $$begin end$$",
        "SET search_path = x",
        "CALL p()",
        "SELECT 'unfinished",
        "SELECT $$unfinished",
        "/* unterminated",
        "SELECT 1\0",
    ] {
        assert!(split_sql(sql).is_err(), "accepted {sql:?}");
    }
    assert!(split_sql("SELECT 'COMMIT; COPY'; -- ROLLBACK\nSELECT 2").is_ok());
}
#[test]
fn creates_first_sql_then_manual_template_and_loads_in_order() {
    let tmp = Temp::new();
    let root = tmp.0.join("migrations");
    let first = create(&root, "initial", &schema()).unwrap();
    assert!(fs::read_to_string(first.join("migration.sql"))
        .unwrap()
        .contains("CREATE TABLE"));
    let second = create(&root, "add_field", &schema()).unwrap();
    assert!(fs::read_to_string(second.join("migration.sql"))
        .unwrap()
        .contains("Add reviewed SQL"));
    let files = load(&root).unwrap();
    assert_eq!(files.len(), 2);
    assert!(files[0].name < files[1].name);
    assert!(files[1].statements.is_empty());
    assert!(create(&root, "../outside", &schema()).is_err());
}
#[test]
fn rejects_unknown_files_missing_scripts_and_invalid_utf8() {
    let tmp = Temp::new();
    let root = tmp.0.join("migrations");
    fs::create_dir(&root).unwrap();
    fs::write(root.join("stray.sql"), "SELECT 1;").unwrap();
    assert!(load(&root).is_err());
    fs::remove_file(root.join("stray.sql")).unwrap();
    let sub = root.join("001_first");
    fs::create_dir(&sub).unwrap();
    assert!(load(&root).is_err());
    fs::write(sub.join("migration.sql"), [0xff]).unwrap();
    assert!(load(&root).is_err());
    fs::write(sub.join("migration.sql"), "SELECT 1;").unwrap();
    fs::write(sub.join("other"), "x").unwrap();
    assert!(load(&root).is_err());
}
#[cfg(unix)]
#[test]
fn rejects_symlinks() {
    use std::os::unix::fs::symlink;
    let tmp = Temp::new();
    let root = tmp.0.join("migrations");
    fs::create_dir(&root).unwrap();
    fs::create_dir(tmp.0.join("outside")).unwrap();
    symlink(tmp.0.join("outside"), root.join("001_link")).unwrap();
    assert!(load(&root).is_err());
}

#[test]
fn sha256_padding_boundaries_and_binary_input() {
    assert_eq!(
        sha256(&vec![b'a'; 55]),
        "9f4390f8d30c2dd92ec9f095b65e2b9ae9b0a925a5258e241c9f1e910f734318"
    );
    assert_eq!(
        sha256(&vec![b'a'; 56]),
        "b35439a4ac6f0948b6d6f9e3c6af0f5f590ce20f1bde7090ef7970686ec6738a"
    );
    assert_eq!(
        sha256(&vec![b'a'; 64]),
        "ffe054fe7ae0cb6dc65c3af9b61d5209f439851db43d0ba5997337df154668eb"
    );
    assert_eq!(
        sha256(&[0, 1, 2, 255]),
        "3d1f57c984978ef98a18378c8166c1cb8ede02c03eeb6aee7e2f121dfeee3e56"
    );
}
#[test]
fn script_size_limit_and_non_script_entries_are_rejected() {
    let tmp = Temp::new();
    let sub = tmp.0.join("001_test");
    fs::create_dir(&sub).unwrap();
    let file = fs::File::create(sub.join("migration.sql")).unwrap();
    file.set_len(8 * 1024 * 1024 + 1).unwrap();
    assert!(load(&tmp.0).is_err());
    fs::remove_file(sub.join("migration.sql")).unwrap();
    fs::write(sub.join(".migration.sql.tmp"), "SELECT 1").unwrap();
    assert!(load(&tmp.0).is_err());
}
#[test]
fn deeply_malformed_sql_never_panics() {
    let alphabet = b"abc012 {}[]@?=()\"/\\*\n.-_;'$";
    let mut seed = 0x12345678_u64;
    for size in 0..100 {
        for _ in 0..32 {
            let mut s = String::new();
            for _ in 0..size {
                seed = seed.wrapping_mul(6364136223846793005).wrapping_add(1);
                s.push(alphabet[(seed >> 32) as usize % alphabet.len()] as char);
            }
            let _ = split_sql(&s);
        }
    }
}

#[test]
fn filesystem_lock_prevents_simultaneous_writers() {
    let tmp = Temp::new();
    let root = tmp.0.join("migrations");
    let lock = tmp.0.join(".migrations.rustorm-write-lock");
    fs::create_dir(&lock).unwrap();
    assert!(create(&root, "initial", &schema()).is_err());
    assert!(!root.exists());
    fs::remove_dir(&lock).unwrap();
    assert!(create(&root, "initial", &schema()).is_ok());
    assert!(!lock.exists());
}
